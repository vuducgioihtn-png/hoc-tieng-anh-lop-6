export type WritingDrillKind =
  | 'rewrite'
  | 'cue_build'
  | 'exclamation'
  | 'wh_question'
  | 'modal_advice'
  | 'conjunction'
  | 'imperative'
  | 'conditional'
  | 'robot_ability';

export interface WritingPatternExample {
  before: string;
  after: string;
  note: string;
}

export interface WritingPattern {
  id: string;
  semester?: 1 | 2;
  title: string;
  englishSubtitle: string;
  units: string;
  accent: 'sky' | 'emerald' | 'amber' | 'violet' | 'rose' | 'teal';
  summary: string;
  formulaBlocks: { label: string; formula: string }[];
  examples: WritingPatternExample[];
  watchOut: string;
}

export interface WritingDrillItem {
  id: string;
  unitId: number;
  kind: WritingDrillKind;
  sourceLabel: string;
  instruction: string;
  promptSentence: string;
  /** Optional phrase inside promptSentence to underline (for Wh-Question drills) */
  underlinedPhrase?: string;
  /** Optional bracketed cue word, e.g. (SMALL) or (take a short rest) */
  cueTag?: string;
  /** Optional starter words shown before the input box */
  starterPrefix?: string;
  /** Full canonical sentence */
  modelAnswer: string;
  /** All accepted variations (checked flexibly ignoring case/extra spaces/final punctuation) */
  acceptedAnswers: string[];
  formulaTip: string;
  explanation: string;
}

export interface ParagraphTopic {
  id: string;
  unitId: number;
  sourceLabel: string;
  titleEn: string;
  titleVi: string;
  wordTarget: [number, number];
  suggestions: string[];
  outlineSteps: {
    part: string;
    guideVi: string;
    starters: string[];
  }[];
  usefulVocab: { word: string; meaning: string }[];
  modelEssay: string;
  modelEssayVi: string;
}

